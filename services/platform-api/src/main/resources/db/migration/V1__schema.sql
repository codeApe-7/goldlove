-- 婚恋智能档案库：完整数据库结构。
--
-- 免费自助注册（手机号 + 密码）→ 档案保存即生效 → 付费或激活码升级 VIP。
-- 除密码之外的字段一律明文存储；密码只存 Argon2id 摘要，永不可逆。
-- Flyway 以 archive_owner 执行；运行时账号 archive_app 没有 DDL 权限，
-- 授权集中在文件末尾，新增表必须在那里显式授权。

CREATE EXTENSION IF NOT EXISTS pgcrypto;

-- ==========================================================================
-- 管理员
-- ==========================================================================

CREATE TABLE admin_user (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(64) NOT NULL,
    display_name VARCHAR(100) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    status VARCHAR(32) NOT NULL,
    last_login_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT uq_admin_user_username UNIQUE (username),
    CONSTRAINT ck_admin_user_status CHECK (status IN ('ACTIVE', 'DISABLED'))
);

-- ==========================================================================
-- 账号与会员
-- ==========================================================================

CREATE TABLE user_account (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    phone VARCHAR(11) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    status VARCHAR(16) NOT NULL DEFAULT 'ACTIVE',
    membership_tier VARCHAR(16) NOT NULL DEFAULT 'FREE',
    membership_credit_minor BIGINT NOT NULL DEFAULT 0,
    last_login_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT uq_user_account_phone UNIQUE (phone),
    -- 位数校验同时钉在库里，应用层不是唯一防线。
    CONSTRAINT ck_user_account_phone CHECK (phone ~ '^1[3-9][0-9]{9}$'),
    CONSTRAINT ck_user_account_status CHECK (status IN ('ACTIVE', 'SUSPENDED', 'CLOSED')),
    CONSTRAINT ck_user_account_tier CHECK (membership_tier IN ('FREE', 'VIP', 'SVIP')),
    CONSTRAINT ck_user_account_credit CHECK (membership_credit_minor >= 0)
);

-- 激活码在生成时就绑定手机号，只有该手机号的账号能兑换。
-- code 明文存储：管理员必须能复读并分发给对应用户。
CREATE TABLE activation_code (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(32) NOT NULL,
    bound_phone VARCHAR(11) NOT NULL,
    granted_tier VARCHAR(16) NOT NULL,
    status VARCHAR(16) NOT NULL DEFAULT 'UNUSED',
    redeemed_by_account_id BIGINT REFERENCES user_account (id),
    redeemed_at TIMESTAMPTZ,
    created_by_admin_id BIGINT NOT NULL REFERENCES admin_user (id),
    note VARCHAR(200),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT uq_activation_code UNIQUE (code),
    CONSTRAINT ck_activation_code_phone CHECK (bound_phone ~ '^1[3-9][0-9]{9}$'),
    CONSTRAINT ck_activation_code_tier CHECK (granted_tier IN ('VIP', 'SVIP')),
    CONSTRAINT ck_activation_code_status CHECK (status IN ('UNUSED', 'USED', 'REVOKED')),
    CONSTRAINT ck_activation_code_used_shape CHECK (
        status <> 'USED'
        OR (redeemed_by_account_id IS NOT NULL AND redeemed_at IS NOT NULL)
    )
);

CREATE INDEX ix_activation_code_phone ON activation_code (bound_phone, created_at DESC);
CREATE INDEX ix_activation_code_status ON activation_code (status, created_at DESC);

-- ==========================================================================
-- 授权书与同意记录
-- ==========================================================================

CREATE TABLE authorization_document (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_code VARCHAR(64) NOT NULL,
    version VARCHAR(32) NOT NULL,
    title VARCHAR(200) NOT NULL,
    content TEXT NOT NULL,
    content_sha256 CHAR(64) NOT NULL,
    status VARCHAR(16) NOT NULL CHECK (status IN ('DRAFT', 'ACTIVE', 'RETIRED')),
    effective_at TIMESTAMPTZ NOT NULL,
    created_by_admin_id BIGINT REFERENCES admin_user (id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_authorization_document_code_version UNIQUE (document_code, version)
);

CREATE UNIQUE INDEX uq_authorization_document_active
    ON authorization_document (document_code) WHERE status = 'ACTIVE';
CREATE INDEX ix_authorization_document_creator
    ON authorization_document (created_by_admin_id);

-- 注册时勾选同意即写入一条，只追加不可改。
-- expires_at 仍记录一年期限用于留痕，但不再作为访问档案的前置条件。
CREATE TABLE authorization_record (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_account_id BIGINT NOT NULL REFERENCES user_account (id),
    authorization_document_id BIGINT NOT NULL REFERENCES authorization_document (id),
    accepted BOOLEAN NOT NULL CHECK (accepted),
    accepted_at TIMESTAMPTZ NOT NULL,
    effective_at TIMESTAMPTZ NOT NULL,
    expires_at TIMESTAMPTZ NOT NULL CHECK (expires_at = effective_at + INTERVAL '1 year'),
    source_page VARCHAR(64) NOT NULL,
    client_ip VARCHAR(45),
    user_agent VARCHAR(500),
    session_reference VARCHAR(64),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_authorization_record_effective_at CHECK (effective_at = accepted_at)
);

CREATE INDEX ix_authorization_record_account
    ON authorization_record (user_account_id, authorization_document_id, expires_at DESC);
CREATE INDEX ix_authorization_record_document
    ON authorization_record (authorization_document_id);

-- ==========================================================================
-- 支付：付费只用于升级 VIP，付款人一定是已登录账号
-- ==========================================================================

CREATE TABLE payment_record (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_account_id BIGINT NOT NULL REFERENCES user_account (id),
    out_trade_no VARCHAR(64) NOT NULL,
    transaction_id VARCHAR(64) NOT NULL,
    channel VARCHAR(24) NOT NULL,
    amount_minor BIGINT NOT NULL,
    currency CHAR(3) NOT NULL DEFAULT 'CNY',
    status VARCHAR(16) NOT NULL DEFAULT 'PAID',
    -- 会员额度累计的幂等锚点：同一笔付款只能计入一次。
    membership_credit_minor BIGINT NOT NULL DEFAULT 0,
    paid_at TIMESTAMPTZ NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_payment_record_out_trade_no UNIQUE (out_trade_no),
    CONSTRAINT uq_payment_record_transaction_id UNIQUE (transaction_id),
    CONSTRAINT ck_payment_record_channel CHECK (channel = 'XPAY_ALIPAY'),
    CONSTRAINT ck_payment_record_amount CHECK (amount_minor > 0),
    CONSTRAINT ck_payment_record_currency CHECK (currency = 'CNY'),
    CONSTRAINT ck_payment_record_status CHECK (status IN ('PAID', 'REFUNDED')),
    CONSTRAINT ck_payment_record_credit CHECK (
        membership_credit_minor >= 0 AND membership_credit_minor <= amount_minor
    )
);

CREATE INDEX ix_payment_record_account ON payment_record (user_account_id, paid_at DESC);

-- out_trade_no 由服务端随机生成，全局唯一，是渠道回调的幂等锚点。
CREATE TABLE payment_order (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    out_trade_no VARCHAR(64) NOT NULL,
    user_account_id BIGINT NOT NULL REFERENCES user_account (id),
    channel VARCHAR(24) NOT NULL,
    amount_minor BIGINT NOT NULL,
    status VARCHAR(16) NOT NULL DEFAULT 'CREATED',
    transaction_id VARCHAR(64),
    paid_at TIMESTAMPTZ,
    payment_record_id BIGINT REFERENCES payment_record (id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT uq_payment_order_out_trade_no UNIQUE (out_trade_no),
    CONSTRAINT ck_payment_order_channel CHECK (channel = 'XPAY_ALIPAY'),
    CONSTRAINT ck_payment_order_status CHECK (status IN ('CREATED', 'PAID', 'CLOSED')),
    CONSTRAINT ck_payment_order_amount CHECK (amount_minor > 0),
    CONSTRAINT ck_payment_order_paid_shape CHECK (
        status <> 'PAID'
        OR (transaction_id IS NOT NULL AND paid_at IS NOT NULL AND payment_record_id IS NOT NULL)
    )
);

CREATE UNIQUE INDEX uq_payment_order_transaction_id
    ON payment_order (transaction_id) WHERE transaction_id IS NOT NULL;
CREATE INDEX ix_payment_order_account ON payment_order (user_account_id, created_at DESC);
CREATE INDEX ix_payment_order_status ON payment_order (status, created_at DESC);

-- ==========================================================================
-- 档案：保存即生效，没有审核与版本快照
