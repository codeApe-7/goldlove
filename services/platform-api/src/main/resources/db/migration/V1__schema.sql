CREATE TABLE profile_field_definition (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    field_code VARCHAR(64) NOT NULL,
    label VARCHAR(100) NOT NULL,
    storage_kind VARCHAR(16) NOT NULL,
    data_type VARCHAR(32) NOT NULL,
    required BOOLEAN NOT NULL,
    enabled BOOLEAN NOT NULL,
    -- 单调标记：一旦有值引用过就不能再改字段编码与类型。
    ever_used BOOLEAN NOT NULL DEFAULT FALSE,
    options_json TEXT,
    sort_order INTEGER NOT NULL,
    instructions TEXT,
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_profile_field_definition_code UNIQUE (field_code),
    CONSTRAINT ck_profile_field_definition_storage_kind CHECK (storage_kind IN ('CORE', 'DYNAMIC')),
    CONSTRAINT ck_profile_field_definition_data_type CHECK (data_type IN (
        'TEXT', 'LONG_TEXT', 'INTEGER', 'DECIMAL', 'DATE', 'BOOLEAN', 'SINGLE_OPTION'
    ))
);

CREATE INDEX ix_profile_field_definition_enabled_sort
    ON profile_field_definition (enabled, sort_order);

CREATE TABLE profile_field_value (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    guest_profile_id BIGINT NOT NULL REFERENCES guest_profile (id),
    field_definition_id BIGINT NOT NULL REFERENCES profile_field_definition (id),
    text_value TEXT,
    integer_value BIGINT,
    decimal_value NUMERIC(18, 2),
    date_value DATE,
    boolean_value BOOLEAN,
    option_value VARCHAR(200),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_profile_field_value_profile_definition
        UNIQUE (guest_profile_id, field_definition_id),
    CONSTRAINT ck_profile_field_value_exactly_one_value CHECK (
        num_nonnulls(text_value, integer_value, decimal_value, date_value, boolean_value, option_value) = 1
    )
