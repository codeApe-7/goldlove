CREATE FUNCTION allow_profile_revision_review_update() RETURNS trigger AS $$
BEGIN
    IF TG_OP = 'DELETE' THEN
        RAISE EXCEPTION 'profile_revision rows are immutable';
    END IF;
    IF (to_jsonb(NEW) - ARRAY['status', 'reviewed_at', 'version'])
            IS DISTINCT FROM (to_jsonb(OLD) - ARRAY['status', 'reviewed_at', 'version']) THEN
        RAISE EXCEPTION 'profile_revision only permits status, reviewed_at, and version updates';
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

