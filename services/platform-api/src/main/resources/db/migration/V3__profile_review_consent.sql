CREATE FUNCTION preserve_profile_field_definition_ever_used() RETURNS trigger AS $$
BEGIN
    IF OLD.ever_used AND NOT NEW.ever_used THEN
        RAISE EXCEPTION 'profile field definition usage cannot be reset';
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE FUNCTION mark_profile_field_definition_ever_used() RETURNS trigger AS $$
BEGIN
    UPDATE profile_field_definition
    SET ever_used = TRUE
    WHERE id = NEW.field_definition_id AND NOT ever_used;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER profile_field_definition_ever_used_monotonic
    BEFORE UPDATE ON profile_field_definition
    FOR EACH ROW EXECUTE FUNCTION preserve_profile_field_definition_ever_used();

